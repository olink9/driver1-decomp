/* HANDWRITTEN ASM */
/* RLE unpacker writing backwards from dest+0x7FFF (signed count byte: <0 = run of next byte, >=0 = literals).
   No C form: every branch delay slot is filled from the branch target while the independent insn right before
   the branch (addiu a1 / addiu a2) stays put - GCC 2.7 reorg's fill_simple_delay_slots would always take it,
   and `bnez a3; addiu a3,a3,1` tests the count before stepping it without a copy (see pilot/AGENT.md f-01). */
__asm__(
    ".set noreorder\n"
    ".macro XBEQZ p0,p1; beqz \\p0, \\p1; .endm\n"
    ".macro XBNEZ p0,p1; bnez \\p0, \\p1; .endm\n"
    ".macro XJ p0; j \\p0; .endm\n"
    ".globl func_00035B5C\n"
    "func_00035B5C:\n"
    "addiu $a2, $a0, 0x7FFF\n"
    ".L00035B60:\n"
    "lb $a3, 0x0($a1)\n"
    "addiu $a1, $a1, 0x1\n"
    "andi $v0, $a3, 0x80\n"
    "XBEQZ $v0, .L00035B9C\n"
    "lbu $v1, 0x0($a1)\n"
    "addiu $a1, $a1, 0x1\n"
    "sb $v1, 0x0($a2)\n"
    "addiu $a2, $a2, -0x1\n"
    ".L00035B80:\n"
    "sb $v1, 0x0($a2)\n"
    "addiu $a2, $a2, -0x1\n"
    "XBNEZ $a3, .L00035B80\n"
    "addiu $a3, $a3, 0x1\n"
    "XJ .L00035BB4\n"
    "sltu $v0,$a2,$a0\n"
    ".L00035B98:\n"
    "lbu $v1, 0x0($a1)\n"
    ".L00035B9C:\n"
    "addiu $a1, $a1, 0x1\n"
    "sb $v1, 0x0($a2)\n"
    "addiu $a2, $a2, -0x1\n"
    "XBNEZ $a3, .L00035B98\n"
    "addiu $a3, $a3, -0x1\n"
    "sltu $v0,$a2,$a0\n"
    ".L00035BB4:\n"
    "XBEQZ $v0, .L00035B60\n"
    "nop\n"
    "jr $ra\n"
    "addu $v0, $a1, $zero\n"
    ".set reorder\n");
